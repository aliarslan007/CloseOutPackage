<?php

declare(strict_types=1);

namespace App\Domains\ChangeOrders\Actions;

use App\Domains\ChangeOrders\DTOs\ChangeOrderDTO;
use App\Domains\ChangeOrders\DTOs\ChangeOrderItemDTO;
use App\Domains\ChangeOrders\Enums\ChangeOrderStatus;
use App\Domains\ChangeOrders\Models\ChangeOrder;
use App\Domains\ChangeOrders\Models\ChangeOrderItem;
use App\Domains\ChangeOrders\Models\ChangeOrderRecipient;
use App\Domains\Projects\Models\Project;
use App\Domains\Users\Models\User;
use Illuminate\Support\Facades\DB;

final class CreateChangeOrderAction
{
    public function __construct(
        private readonly AttachChangeOrderPhotosAction $attachPhotosAction,
    ) {}

    /**
     * @param  list<int>  $recipientIds  Customer user ids (already validated against project access).
     * @param  array<string, string>  $tokens  recipient user id => raw token (generated by caller on send only)
     */
    public function execute(Project $project, ChangeOrderDTO $dto, User $creator, array $recipientIds = []): ChangeOrder
    {
        return DB::transaction(function () use ($project, $dto, $creator, $recipientIds): ChangeOrder {
            $changeOrder = ChangeOrder::create([
                'project_id' => $project->id,
                'created_by' => $creator->id,
                'title' => $dto->title,
                'description' => $dto->description,
                'change_order_date' => $dto->changeOrderDate,
                'status' => ChangeOrderStatus::DRAFT,
                'total_amount' => $dto->includedTotal(),
            ]);

            $this->syncItems($changeOrder, $dto->items);
            $this->syncRecipients($changeOrder, $recipientIds);

            if ($dto->mediaAssetIds !== []) {
                $this->attachPhotosAction->execute($changeOrder, $dto->mediaAssetIds, $creator);
            }

            return $changeOrder->refresh();
        });
    }

    /**
     * @param  list<ChangeOrderItemDTO>  $items
     */
    public function syncItems(ChangeOrder $changeOrder, array $items): void
    {
        $changeOrder->items()->delete();

        foreach ($items as $index => $item) {
            ChangeOrderItem::create([
                'change_order_id' => $changeOrder->id,
                'sort_order' => $index + 1,
                'description' => $item->description,
                'vendor_name' => $item->vendorName,
                'category' => $item->category,
                'amount' => $item->amount,
                'is_included' => $item->isIncluded,
                'cost_absorbed_by_solucomp' => $item->costAbsorbedBySolucomp,
                'customer_decision' => $item->customerDecision,
                'customer_decision_note' => $item->customerDecisionNote,
            ]);
        }

        $includedTotal = collect($items)->sum(
            fn ($item) => ($item->isIncluded && ! $item->costAbsorbedBySolucomp) ? $item->amount : 0,
        );
        $changeOrder->update(['total_amount' => $includedTotal]);
    }

    /**
     * @param  list<int>  $recipientIds
     */
    public function syncRecipients(ChangeOrder $changeOrder, array $recipientIds): void
    {
        if ($recipientIds === []) {
            return;
        }

        foreach ($recipientIds as $userId) {
            ChangeOrderRecipient::firstOrCreate([
                'change_order_id' => $changeOrder->id,
                'user_id' => $userId,
            ]);
        }
    }
}
